"""Enumerator and counter of LinFeas(P) for case `so` (sync points + observed reads).

Linearizations are generated by an iterative depth-first search over the trace poset
(add any currently minimal node, in increasing index order). When the setup has observed
reads, a set of *effect states* is carried along the prefix and a branch is cut as soon
as that set becomes empty.

Effect-state model (fixed prefix of L):
    state = (pending, blocks, vals)
      pending  bitmask of relevant actions that have started but whose effect point has
               not been placed yet
      blocks   current content of every block
      vals     values returned by the (unobserved) reads that some relevant write uses
Effects of pending actions may be placed, in any order, in the gap before any node.
Start nodes do nothing to the data, so every effect can be postponed to the gap just
before the next *done* node without changing the relative order of effects. The sets
kept along the prefix are therefore "open": the effects of still pending actions are
explored only when the done node of some action forces its effect.
"""

from __future__ import annotations

from typing import Iterator

from harness import terms as T
from harness.capabilities import Capabilities
from harness.lin.api import CountResult, LinCounter, LinEnumerator
from harness.registry import register

CAPS = Capabilities(rcw=False, sync=True, observed_reads=True)
_DEAD_CAP = 1_000_000


class _Feas:
    """Incremental feasibility tracker over a linearization prefix."""

    def __init__(self, setup) -> None:
        acts = setup.actions
        self.acts = acts
        observed = [a.id for a in acts.values() if a.kind == "read" and a.observed is not None]
        self.active = bool(observed)
        if not self.active:
            return

        dep_cache: dict[str, set[str]] = {}

        def deps(aid: str) -> set[str]:
            """Reads transitively referenced by the data of write ``aid``."""
            got = dep_cache.get(aid)
            if got is not None:
                return got
            a = acts[aid]
            out: set[str] = set()
            if a.data is not None:
                for r in T.refs(a.data):
                    b = acts[r]
                    if b.kind == "read":
                        out.add(r)
                    else:
                        out |= deps(r)
            dep_cache[aid] = out
            return out

        # Relevant reads/writes: a fixpoint starting from the observed reads.
        rel_reads = set(observed)
        while True:
            rblocks = {acts[r].block for r in rel_reads}
            rel_writes = {a.id for a in acts.values() if a.kind != "read" and a.block in rblocks}
            new = set(rel_reads)
            for w in rel_writes:
                new |= deps(w)
            if new == rel_reads:
                break
            rel_reads = new

        needed_vals: set[str] = set()
        for w in rel_writes:
            needed_vals |= deps(w)

        rel = [a.id for a in acts.values() if a.id in rel_reads or a.id in rel_writes]
        self.rel = rel
        self.slot_of: dict[str, int] = {}
        for aid in rel:
            a = acts[aid]
            if a.kind == "read" and a.observed is None and aid in needed_vals:
                self.slot_of[aid] = len(self.slot_of)

        P = setup.poset
        n = len(P)
        self.start_of = [-1] * n
        self.done_of = [-1] * n
        self.is_read: list[bool] = []
        self.block: list[int] = []
        self.obs: list = []
        self.slot: list[int] = []
        self.static: list = []
        for k, aid in enumerate(rel):
            a = acts[aid]
            self.start_of[P.start_node[aid]] = k
            self.done_of[P.done_node[aid]] = k
            self.is_read.append(a.kind == "read")
            self.block.append(a.block)
            self.obs.append(a.observed if a.kind == "read" else None)
            self.slot.append(self.slot_of.get(aid, -1))
            if a.kind == "read":
                self.static.append(None)
            elif setup.depends_on_reads(aid):
                self.static.append(None)
            else:
                self.static.append(setup.static_content(aid))
        self.rel_ids = rel
        self.init_state = frozenset([(0, tuple(setup.init), (None,) * len(self.slot_of))])
        self._cache: dict = {}

    # ---------------------------------------------------------------- data

    def _content(self, aid: str, V: tuple):
        a = self.acts[aid]
        if a.data is None:
            return T.Unk(aid)

        def look(x: str):
            b = self.acts[x]
            if b.kind == "read":
                if b.observed is not None:
                    return b.observed
                return V[self.slot_of[x]]
            return self._content(x, V)

        return T.substitute(a.data, look)

    def _apply(self, k: int, u):
        p, B, V = u
        nb = p & ~(1 << k)
        b = self.block[k]
        if self.is_read[k]:
            val = B[b]
            o = self.obs[k]
            if o is not None and val != o:
                return None
            s = self.slot[k]
            if s >= 0:
                V = V[:s] + (val,) + V[s + 1:]
            return (nb, B, V)
        c = self.static[k]
        if c is None:
            key = (k, V)
            c = self._cache.get(key)
            if c is None:
                c = self._content(self.rel_ids[k], V)
                if len(self._cache) < 200_000:
                    self._cache[key] = c
        return (nb, B[:b] + (c,) + B[b + 1:], V)

    # ---------------------------------------------------------------- steps

    def _done(self, S, k: int):
        bit = 1 << k
        out = set()
        seen = set()
        frontier = []
        for s in S:
            if s[0] & bit:
                if s not in seen:
                    seen.add(s)
                    frontier.append(s)
            else:
                out.add(s)
        apply = self._apply
        while frontier:
            u = frontier.pop()
            t = apply(k, u)
            if t is not None:
                out.add(t)
            p = u[0] & ~bit
            while p:
                lb = p & -p
                p ^= lb
                v = apply(lb.bit_length() - 1, u)
                if v is not None and v not in seen:
                    seen.add(v)
                    frontier.append(v)
        return frozenset(out)

    def step(self, S, x: int):
        k = self.start_of[x]
        if k >= 0:
            bit = 1 << k
            return frozenset([(p | bit, B, V) for (p, B, V) in S])
        k = self.done_of[x]
        if k >= 0:
            return self._done(S, k)
        return S


def _dfs(P, step, s0) -> Iterator[tuple[int, ...]]:
    n = len(P)
    if n == 0:
        yield ()
        return
    succs = P.succs
    indeg = [len(p) for p in P.preds]
    ready = {x for x in range(n) if indeg[x] == 0}
    order: list[int] = []
    states = [s0]
    mask = 0
    use_state = step is not None
    dead: set | None = set() if use_state else None
    emitted = 0
    # frame: [choices, next index, placed flag, emitted count at push]
    stack = [[sorted(ready), 0, False, 0]]
    while stack:
        fr = stack[-1]
        if fr[2]:
            x = order.pop()
            for y in succs[x]:
                if indeg[y] == 0:
                    ready.discard(y)
                indeg[y] += 1
            ready.add(x)
            mask ^= 1 << x
            if use_state:
                states.pop()
            fr[2] = False
        choices = fr[0]
        i = fr[1]
        if i >= len(choices):
            stack.pop()
            if dead is not None and stack and emitted == fr[3] and len(dead) < _DEAD_CAP:
                dead.add((mask, states[-1]))
            continue
        x = choices[i]
        fr[1] = i + 1
        ns = None
        if use_state:
            ns = step(states[-1], x)
            if not ns:
                continue
        ready.discard(x)
        mask |= 1 << x
        order.append(x)
        for y in succs[x]:
            indeg[y] -= 1
            if indeg[y] == 0:
                ready.add(y)
        if use_state:
            states.append(ns)
        fr[2] = True
        if len(order) == n:
            emitted += 1
            yield tuple(order)
            continue
        if dead is not None and (mask, ns) in dead:
            continue
        stack.append([sorted(ready), 0, False, emitted])


@register
class Opus55SoEnumerator(LinEnumerator):
    name = "opus55_1-so-enum"
    description = "DFS over linear extensions, pruned by an incremental effect-state set for observed reads"
    capabilities = CAPS

    def enumerate(self, setup) -> Iterator[tuple[int, ...]]:
        P = setup.poset
        feas = _Feas(setup)
        if feas.active:
            return _dfs(P, feas.step, feas.init_state)
        return _dfs(P, None, None)


@register
class Opus55SoCounter(LinCounter):
    name = "opus55_1-so-count"
    description = "Layered DP over downsets (and effect-state sets when reads are observed)"
    capabilities = CAPS

    def count(self, setup) -> CountResult:
        P = setup.poset
        n = len(P)
        predmask = [0] * n
        for x in range(n):
            m = 0
            for u in P.preds[x]:
                m |= 1 << u
            predmask[x] = m
        full = (1 << n) - 1

        layer: dict = {0: 1}
        for _ in range(n):
            nxt: dict = {}
            for mask, c in layer.items():
                for x in range(n):
                    if not (mask >> x) & 1 and (predmask[x] & mask) == predmask[x]:
                        m2 = mask | (1 << x)
                        nxt[m2] = nxt.get(m2, 0) + c
            layer = nxt
        lin = layer.get(full, 0)

        feasible = None
        feas = _Feas(setup)
        if feas.active:
            fl: dict = {(0, feas.init_state): 1}
            for _ in range(n):
                nxt = {}
                for (mask, S), c in fl.items():
                    for x in range(n):
                        if not (mask >> x) & 1 and (predmask[x] & mask) == predmask[x]:
                            ns = feas.step(S, x)
                            if ns:
                                key = (mask | (1 << x), ns)
                                nxt[key] = nxt.get(key, 0) + c
                fl = nxt
            feasible = sum(fl.values())
        return CountResult(linearizations=lin, feasible=feasible, method="downset-dp")
